/** "just now", "5 min ago", "3 h ago", "2 days ago". `now` is a parameter so tests need no clock tricks. */
export function relativeTime(iso: string, now: number = Date.now()): string {
  const seconds = Math.max(0, Math.round((now - Date.parse(iso)) / 1000));
  if (Number.isNaN(seconds)) return '';
  if (seconds < 60) return 'just now';
  const minutes = Math.floor(seconds / 60);
  if (minutes < 60) return `${minutes} min ago`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours} h ago`;
  const days = Math.floor(hours / 24);
  return `${days} ${days === 1 ? 'day' : 'days'} ago`;
}

/** The exact time, in the viewer's own locale, for tooltips and the detail panel. */
export const exactTime = (iso: string): string => new Date(iso).toLocaleString();
